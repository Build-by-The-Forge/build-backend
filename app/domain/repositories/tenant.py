from __future__ import annotations

from typing import List, Optional, Protocol

from app.domain.tenant.academic_session import AcademicSession
from app.domain.tenant.department import Department
from app.domain.tenant.faculty import Faculty
from app.domain.tenant.level import Level
from app.domain.tenant.membership import Membership
from app.domain.tenant.programme import Programme
from app.domain.tenant.semester import Semester
from app.domain.tenant.tenant import Tenant


class TenantRepository(Protocol):
    def add(self, tenant: Tenant) -> None: ...
    def get_by_id(self, tenant_id: str) -> Optional[Tenant]: ...
    def get_by_slug(self, slug: str) -> Optional[Tenant]: ...
    def list_all(self) -> List[Tenant]: ...


class FacultyRepository(Protocol):
    def add(self, faculty: Faculty) -> None: ...
    def get_by_id(self, faculty_id: str) -> Optional[Faculty]: ...
    def list_by_tenant(self, tenant_id: str) -> List[Faculty]: ...


class DepartmentRepository(Protocol):
    def add(self, dept: Department) -> None: ...
    def get_by_id(self, dept_id: str) -> Optional[Department]: ...
    def list_by_faculty(self, faculty_id: str) -> List[Department]: ...
    def list_by_tenant(self, tenant_id: str) -> List[Department]: ...


class ProgrammeRepository(Protocol):
    def add(self, prog: Programme) -> None: ...
    def list_by_department(self, dept_id: str) -> List[Programme]: ...


class LevelRepository(Protocol):
    def add(self, level: Level) -> None: ...
    def list_by_tenant(self, tenant_id: str) -> List[Level]: ...


class AcademicSessionRepository(Protocol):
    def add(self, session: AcademicSession) -> None: ...
    def list_by_tenant(self, tenant_id: str) -> List[AcademicSession]: ...
    def get_current(self, tenant_id: str) -> Optional[AcademicSession]: ...


class SemesterRepository(Protocol):
    def add(self, sem: Semester) -> None: ...
    def list_by_session(self, session_id: str) -> List[Semester]: ...


class MembershipRepository(Protocol):
    def add(self, m: Membership) -> None: ...
    def get_by_tenant_user(
        self, tenant_id: str, user_id: str
    ) -> Optional[Membership]: ...
